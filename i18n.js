function tsukihiNormalizeLanguage(value) {
  return value === 'zh' ? 'zh' : TSUKIHI_DEFAULT_LANGUAGE;
}

function tsukihiTranslate(language, key, variables = {}) {
  const locale = tsukihiNormalizeLanguage(language);
  const template = TSUKIHI_MESSAGES[locale]?.[key]
    ?? TSUKIHI_MESSAGES[TSUKIHI_DEFAULT_LANGUAGE]?.[key]
    ?? key;
  return String(template).replace(/\{(\w+)\}/g, (match, name) => (
    Object.prototype.hasOwnProperty.call(variables, name) ? String(variables[name]) : match
  ));
}

function tsukihiGetLanguage() {
  return new Promise((resolve) => {
    chrome.storage.local.get('tsukihiLanguage', (result) => {
      if (chrome.runtime.lastError) {
        resolve(TSUKIHI_DEFAULT_LANGUAGE);
        return;
      }
      resolve(tsukihiNormalizeLanguage(result.tsukihiLanguage));
    });
  });
}

function tsukihiSetLanguage(language) {
  const normalized = tsukihiNormalizeLanguage(language);
  return new Promise((resolve, reject) => {
    chrome.storage.local.set({ tsukihiLanguage: normalized }, () => {
      if (chrome.runtime.lastError) reject(new Error(chrome.runtime.lastError.message));
      else resolve(normalized);
    });
  });
}

function tsukihiApplyPageTranslations(language, root = document) {
  root.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = tsukihiTranslate(language, element.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-title]').forEach((element) => {
    element.title = tsukihiTranslate(language, element.dataset.i18nTitle);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    element.placeholder = tsukihiTranslate(language, element.dataset.i18nPlaceholder);
  });
  root.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
    element.setAttribute('aria-label', tsukihiTranslate(language, element.dataset.i18nAriaLabel));
  });
  if (document.documentElement.dataset.i18nDocumentTitle) {
    document.title = tsukihiTranslate(language, document.documentElement.dataset.i18nDocumentTitle);
  }
  document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
}

function tsukihiBindLanguageSelect(select, onChange) {
  if (!select) return;
  select.value = tsukihiNormalizeLanguage(select.value);
  select.addEventListener('change', async () => {
    const language = await tsukihiSetLanguage(select.value);
    await onChange(language);
  });
}

function tsukihiWatchLanguage(onChange) {
  chrome.storage.onChanged.addListener((changes, areaName) => {
    if (areaName !== 'local' || !changes.tsukihiLanguage) return;
    onChange(tsukihiNormalizeLanguage(changes.tsukihiLanguage.newValue));
  });
}
